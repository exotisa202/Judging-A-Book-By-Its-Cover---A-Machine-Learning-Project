"""Build a self-contained visual report from the actual offline retrieval demo."""
import argparse
import base64
from html import escape
from pathlib import Path
import cv2
from cover_match import rank, synthetic_images


def image_url(image):
    ok, data = cv2.imencode('.png', image)
    if not ok:
        raise ValueError('PNG encoding failed')
    return 'data:image/png;base64,' + base64.b64encode(data).decode('ascii')


def build_report():
    query, candidates = synthetic_images()
    matches = rank(query, candidates)
    cards = ''.join(
        f'<div class="cover"><img alt="{escape(name)}" src="{image_url(image)}">'
        f'<p>{escape(name)}</p></div>' for name, image in candidates)
    rows = ''.join(
        f'<tr><td>{i}</td><td>{escape(row["image"])}</td>'
        f'<td>{row["histogram_correlation"]:.4f}</td><td>{row["ssim"]:.4f}</td>'
        f'<td>{row["sift_matches"]}</td></tr>' for i, row in enumerate(matches, 1))
    return '''<!doctype html><html lang="en"><meta charset="utf-8">
<title>Book-cover retrieval · offline demo</title>
<style>
*{box-sizing:border-box}body{margin:0;background:#f3f5f7;color:#192b39;font:16px system-ui,sans-serif}
main{max-width:1120px;margin:36px auto;background:white;padding:38px 46px;border:1px solid #dce3e8;border-radius:16px}
.tag{font:700 12px system-ui;letter-spacing:2px;color:#327366}h1{font-size:36px;letter-spacing:-1px;margin:12px 0}
p{color:#526575;line-height:1.5}.pipeline{display:flex;gap:16px;margin:28px 0}.stage{flex:1;background:#eef5f3;border-radius:8px;padding:17px;font-weight:600}.stage small{display:block;font-weight:400;margin-top:6px;color:#526575}.visuals{display:flex;gap:30px;margin:24px 0}.query{border-right:1px solid #dce3e8;padding-right:32px}.covers{display:flex;gap:25px}.cover img,.query img{width:160px;height:160px;image-rendering:pixelated;border:1px solid #dce3e8;border-radius:5px}.cover p{font-size:12px}h2{font-size:18px;margin:0 0 14px}table{width:100%;border-collapse:collapse;margin-top:20px;font-size:14px}td,th{text-align:left;padding:15px 10px;border-bottom:1px solid #dce3e8}th{color:#526575;font-size:12px}.note{background:#fff6e5;border-left:3px solid #d8a743;padding:13px 18px;font-size:13px;margin-top:24px}footer{font:12px monospace;color:#526575;margin-top:24px}
</style><main><div class="tag">COMPUTER VISION / REPRODUCIBLE DEMO</div>
<h1>Judging a Book by Its Cover</h1>
<p>Inspect a three-stage visual retrieval pipeline, without external downloads.</p>
<div class="pipeline"><div class="stage">01 / Histogram<small>8 × 8 × 8 colour bins</small></div><div class="stage">02 / SSIM<small>Structural similarity filter</small></div><div class="stage">03 / SIFT<small>Local feature matching</small></div></div>
<div class="visuals"><div class="query"><h2>Query</h2><img alt="Synthetic patterned query" src="''' + image_url(query) + '''"><p>Synthetic test image</p></div><div><h2>Gallery / 2 candidates</h2><div class="covers">''' + cards + '''</div></div></div>
<h2>Computed retrieval results</h2><table><thead><tr><th>Rank</th><th>Candidate</th><th>Histogram</th><th>SSIM</th><th>SIFT matches</th></tr></thead><tbody>''' + rows + '''</tbody></table>
<div class="note"><strong>Smoke test, not research accuracy.</strong> These generated patterns verify retrieval mechanics. They are not book covers, genre labels, or evidence of real-world classification performance.</div>
<footer>Generated by python demo_report.py · deterministic seed 42 · no network calls</footer></main></html>'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path('demo.html'))
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build_report(), encoding='utf-8')
    print(f'Wrote {args.output}')


if __name__ == '__main__':
    main()
